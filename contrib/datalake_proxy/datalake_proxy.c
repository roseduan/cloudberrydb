/*
 * The generated, ordered classpath for the selected transport.
 *
 * Read from a file rather than assembled here because the order comes from
 * Maven's dependency resolution, which only the build knows; see
 * contrib/datalake_agent/install-layout.sh.  A missing or empty file is fatal:
 * starting the agent with a guessed classpath would either fail obscurely at
 * some later class load or, worse, succeed with the wrong duplicate class.
 */
static char *
readAgentClassPath(const char *pkglib_path)
{
	char		path[MAXPGPATH];
	FILE	   *fp;
	long		size;
	char	   *buffer;

	snprintf(path, sizeof(path), "%s/java/%s.cp", pkglib_path,
			 datalake_agent_transport == DATALAKE_AGENT_TRANSPORT_GRPC
			 ? "grpc" : "rest");

	fp = fopen(path, "r");
	if (fp == NULL)
		ereport(ERROR,
				(errcode_for_file_access(),
				 errmsg("could not open the dlagent classpath file \"%s\": %m", path),
				 errhint("It is generated by \"make install\" in contrib/datalake_agent.")));

	if (fseek(fp, 0, SEEK_END) != 0 || (size = ftell(fp)) < 0)
	{
		fclose(fp);
		ereport(ERROR, (errmsg("could not size the dlagent classpath file \"%s\"", path)));
	}
	rewind(fp);

	buffer = palloc(size + 1);
	if (size > 0 && fread(buffer, 1, size, fp) != (size_t) size)
	{
		fclose(fp);
		ereport(ERROR, (errmsg("could not read the dlagent classpath file \"%s\"", path)));
	}
	buffer[size] = '\0';
	fclose(fp);

	/* The file ends with a newline; execvp would pass it through verbatim. */
	while (size > 0 && (buffer[size - 1] == '\n' || buffer[size - 1] == '\r'))
		buffer[--size] = '\0';

	if (size == 0)
		ereport(ERROR,
				(errmsg("the dlagent classpath file \"%s\" is empty", path)));

	/*
	 * The entries are relative to pkglib/java (see install-layout.sh), so
	 * resolve them against the pkglib this postmaster is actually running
	 * from.  Writing absolute paths at install time tied the agent to the
	 * install prefix: once the tree was relocated java got a classpath of
	 * missing files, exited immediately, and every catalog call failed with
	 * "Could not connect to server".  An absolute entry is kept as is.
	 */
	{
		StringInfoData resolved;
		char	   *entry;
		char	   *saveptr = NULL;
		bool		first = true;

		initStringInfo(&resolved);
		for (entry = strtok_r(buffer, ":", &saveptr); entry != NULL;
			 entry = strtok_r(NULL, ":", &saveptr))
		{
			if (!first)
				appendStringInfoChar(&resolved, ':');
			if (entry[0] == '/')
				appendStringInfoString(&resolved, entry);
			else
				appendStringInfo(&resolved, "%s/java/%s", pkglib_path, entry);
			first = false;
		}
		pfree(buffer);
		buffer = resolved.data;
	}

	return buffer;
}



