static const struct config_enum_entry agent_transport_options[] = {
	{"rest", DATALAKE_AGENT_TRANSPORT_REST, false},
	{"grpc", DATALAKE_AGENT_TRANSPORT_GRPC, false},
	{NULL, 0, false}
};

/*
 * Reject grpc on a build that has no gRPC support, rather than failing later
 * with a confusing connection error.  contrib/datalake_agent/grpcxx.mk leaves
 * HAVE_GRPCXX undefined when grpc++ >= 1.50 was not found, which is a
 * supported configuration: the build succeeds and speaks REST only.  This
 * module and datalake_fdw both decide through that file, so one check covers
 * both sides.
 */
static bool
check_agent_transport(int *newval, void **extra, GucSource source)
{
#ifndef HAVE_GRPCXX
	if (*newval == DATALAKE_AGENT_TRANSPORT_GRPC)
	{
		GUC_check_errmsg("datalake.agent_transport cannot be set to \"grpc\"");
		GUC_check_errdetail("This build has no gRPC support "
							"because grpc++ >= 1.50 was not found when it was built.");
		GUC_check_errhint("Rebuild with grpc++ available, or use datalake.agent_transport=rest.");
		return false;
	}
#endif
	return true;
}

void
_PG_init(void)
{
	if (!process_shared_preload_libraries_in_progress)
		return;

	/* can't define PGC_POSTMASTER variable after startup */
	DefineCustomBoolVariable("datalake_proxy.register_datalake_proxy",
							 "Starts the datalake proxy worker.",
							 NULL,
							 &register_datalake_proxy,
							 true,
							 PGC_POSTMASTER,
							 0,
							 NULL,
							 NULL,
							 NULL);

	/*
	 * THE TRANSPORT SWITCH.  Defined here, in the preloaded module, rather
	 * than in datalake_fdw: the postmaster must know which agent to launch
	 * before any backend has touched a foreign table, so the only module
	 * guaranteed to be loaded when the answer is needed is this one (see
	 * dlagent_transport.h for the .so-level reason).
	 *
	 * PGC_POSTMASTER because the two transports are two different agent jars
	 * listening on two different ports, and the jar is chosen once, here, when
	 * the agent starts.  Letting a session change it would leave the backend
	 * speaking gRPC to a REST agent, which fails in a way that looks like a
	 * network problem rather than a configuration one.  Switching therefore
	 * costs a cluster restart, and costs nothing else: no DDL, no catalog
	 * change, no SERVER or foreign table rebuild.
	 */
#ifndef HAVE_GRPCXX

	/*
	 * Refuse grpc here, loudly, and not only in check_agent_transport.  The
	 * postmaster reads postgresql.conf before it loads this library, so a
	 * configured "grpc" is already a placeholder when the variable is defined
	 * below, and defining it re-applies the placeholder with elevel WARNING:
	 * the check hook's refusal becomes one log line, the value stays at this
	 * build's rest default, and the cluster comes up quietly using the
	 * transport nobody asked for.
	 * An ERROR here, before the definition, stops the postmaster instead.
	 */
	if (dlagent_transport_from_string(GetConfigOption(DLAGENT_GUC_TRANSPORT,
													 true, false)) ==
		DATALAKE_AGENT_TRANSPORT_GRPC)
		ereport(ERROR,
				(errcode(ERRCODE_FEATURE_NOT_SUPPORTED),
				 errmsg("datalake.agent_transport cannot be set to \"grpc\""),
				 errdetail("This build has no gRPC support "
						   "because grpc++ >= 1.50 was not found when it was built."),
				 errhint("Rebuild with grpc++ available, or use datalake.agent_transport=rest.")));
#endif

	DefineCustomEnumVariable(DLAGENT_GUC_TRANSPORT,
							 "Wire protocol used to talk to the datalake agent",
							 "grpc (the default) uses the gRPC agent; rest uses the Spring "
							 "Boot agent over HTTP, and is the default only on a build "
							 "without gRPC support. Both speak the same JSON payloads, so "
							 "switching needs no DDL and no catalog change -- only a cluster "
							 "restart, because datalake_proxy chooses the agent jar at startup.",
							 &datalake_agent_transport,
							 DATALAKE_AGENT_DEFAULT_TRANSPORT,
							 agent_transport_options,
							 PGC_POSTMASTER,
							 0,
							 check_agent_transport,
							 NULL,
							 NULL);

	DefineCustomIntVariable(DLAGENT_GUC_GRPC_PORT,
							"Port the gRPC datalake agent listens on",
							"Only used when datalake.agent_transport = grpc. It is a "
							"separate port from the REST agent's so that a leftover "
							"process from the other transport fails to connect rather "
							"than half-working.",
							&datalake_agent_grpc_port,
							DATALAKE_AGENT_DEFAULT_GRPC_PORT,
							1, 65535,
							PGC_POSTMASTER,
							0,
							NULL,
							NULL,
							NULL);

	/*
	 * ONE CEILING, BOTH DIRECTIONS, BOTH LANGUAGES.
	 *
	 * See dlagent_transport.h for why a single setting rather than a constant
	 * on each side.  It belongs to this module for the same reason the port
	 * does: the value has to be on the agent's command line, and this is the
	 * module that builds it.
	 *
	 * PGC_POSTMASTER because the server half is applied when the agent binds
	 * its port, so a session that lowered it would be describing a limit the
	 * running agent does not have.
	 */
	DefineCustomIntVariable(DLAGENT_GUC_RPC_MAX_MESSAGE_SIZE,
							"Largest single gRPC message the agent and the FDW will exchange",
							"Only used when datalake.agent_transport = grpc. Both the client "
							"and the agent take this one value, because gRPC enforces the "
							"limit on whichever side RECEIVES: raising only one of them makes "
							"a large request fail under grpc that succeeds under rest. A "
							"request carries the whole file list as a single message, at "
							"roughly 200 bytes per file.",
							&datalake_rpc_max_message_size_mb,
							DATALAKE_AGENT_DEFAULT_RPC_MAX_MESSAGE_SIZE_MB,
							1, DATALAKE_AGENT_MAX_RPC_MAX_MESSAGE_SIZE_MB,
							PGC_POSTMASTER,
							GUC_UNIT_MB,
							NULL,
							NULL,
							NULL);

	/*
	 * The default depends on how long the agent takes to become ready, which
	 * depends on the transport: the REST agent needs 15-30s for Spring, the
	 * gRPC agent a few seconds.  Reading datalake_agent_transport here is safe
	 * because the two lines above have just defined it, which is the other
	 * reason the transport GUC belongs to this module.
	 */
	DefineCustomIntVariable("datalake_proxy.restart_time",
							"Seconds to wait before restarting a crashed dlagent",
							"Defaults to 30 for the REST transport, whose Spring startup "
							"takes that long, and to 5 for gRPC, which reaches SERVING in "
							"about a second.",
							&datalake_proxy_restart_time,
							datalake_agent_transport == DATALAKE_AGENT_TRANSPORT_GRPC ? 5 : 30,
							1, 3600,
							PGC_POSTMASTER,
							GUC_UNIT_S,
							NULL,
							NULL,
							NULL);

	DefineCustomIntVariable("datalake_proxy.dlagent_memory_limit",
							 "Sets the maximum memory to be used for dlagent guc unit mb.",
							 "Sets dlagent memory limit.",
							 &dlagent_memory_limit,
							 2048,
							 512, MAX_KILOBYTES / 1024,
							 PGC_SIGHUP,
							 GUC_UNIT_MB,
							 NULL,
							 NULL,
							 NULL);


	EmitWarningsOnPlaceholders("datalake_proxy");

	if (register_datalake_proxy)
		datalake_proxy_start_worker();
}

bool
IsUnderMasterDispatchMode(void)
{
	if (Gp_role == GP_ROLE_DISPATCH)
		return true;

	return false;
}

static void
datalake_proxy_start_worker(void)
{
	BackgroundWorker worker;
	BackgroundWorkerHandle *handle;
	BgwHandleStatus status;
	pid_t		pid;

	if (!IsUnderMasterDispatchMode())
	{
		return;
	}

	MemSet(&worker, 0, sizeof(BackgroundWorker));
	worker.bgw_flags = BGWORKER_SHMEM_ACCESS;
	worker.bgw_start_time = BgWorkerStart_RecoveryFinished;
	/*
	 * Restart delay after a crash.  bgw_restart_time = 0 (the MemSet default)
	 * means "respawn immediately", which during transient failures (e.g.
	 * ENOSPC on relcache init file write) creates a tight 6-second cascade
	 * loop that floods the log and never lets the child dlagent JVM finish
	 * startup.
	 *
	 * 30s was sized for the REST agent, whose Spring Boot startup takes
	 * 15-30s.  The gRPC agent reaches SERVING in about a second, so waiting
	 * 30s there is 30s of a datalake that answers nothing.  The value is now
	 * a GUC with a transport-dependent default, and the number for grpc is to
	 * be confirmed against a measured cold start before it is relied on.
	 */
	worker.bgw_restart_time = datalake_proxy_restart_time;

	strcpy(worker.bgw_library_name, "datalake_proxy");
	strcpy(worker.bgw_function_name, "datalake_proxy_main");
	strcpy(worker.bgw_name, "datalake proxy process");
	strcpy(worker.bgw_type, "datalake proxy process");

	if (process_shared_preload_libraries_in_progress)
	{
		RegisterBackgroundWorker(&worker);
		return;
	}
	/* must set notify PID to wait for startup */
	worker.bgw_notify_pid = MyProcPid;

	if (!RegisterDynamicBackgroundWorker(&worker, &handle))
		ereport(ERROR,
				(errcode(ERRCODE_INSUFFICIENT_RESOURCES),
				 errmsg("could not register background process"),
				 errhint("You may need to increase max_worker_processes.")));

	status = WaitForBackgroundWorkerStartup(handle, &pid);
	if (status != BGWH_STARTED)
		ereport(ERROR,
				(errcode(ERRCODE_INSUFFICIENT_RESOURCES),
				 errmsg("could not start background process"),
				 errhint("More details may be available in the server log.")));
}

void
datalake_proxy_main(Datum main_arg)
{
	pid_t proxyPid;
	pid_t pid = getpid();

	pqsignal(SIGTERM, DataLakeQuickdie);
	pqsignal(SIGQUIT, DataLakeQuickdie);

	char	   *classPath;

	/* hashdata 3x default block sigquit */
	sigdelset(&BlockSig, SIGQUIT);

	/*
	 * Read the classpath here, in the bgworker, where an ERROR is an ordinary
	 * worker exit.  In the forked child it could not be: the child shares
	 * this process's PGPROC and exit callbacks, and an ERROR there would run
	 * them as if it were the worker.
	 */
	classPath = readAgentClassPath(pkglib_path);

	switch (proxyPid = fork_process())
	{
		case -1:
			ereport(ERROR,
			        (errmsg("could not fork datalake proxy process: %m")));
			break;
		case 0:
			startProxyProcess(pid, classPath);
			/* not reached: startProxyProcess either execs or _exit()s */
			_exit(EXIT_FAILURE);
	}

	waitForAgentReady(proxyPid);

	DataLakeProxyLoop(proxyPid);

	proc_exit(0);
}

static void
startProxyProcess(pid_t pid, char *classPath)
{
	int   i = 0;
	/*
	 * Sized for every argument this function can append plus the NULL:
	 * java, -Xms, -Xmx, -XX:+ExitOnOutOfMemoryError, -cp, <classpath>,
	 * <main class>, --parent.pid, --dlagent.grpc.port,
	 * --dlagent.rpc_max_message_size, --gopher.enabled=false, NULL = 12.
	 * Two spare, because overrunning it writes past the frame silently.
	 */
	char *proxyArgs[14];
	char  parentPid[128];
	char  maxMemoryLimit[128];
	char  grpcPort[64];
	char  rpcMaxMessageSize[64];

	proxyArgs[i++] = "java";
	proxyArgs[i++] = "-Xms512m";

	snprintf(maxMemoryLimit, sizeof(maxMemoryLimit), "-Xmx%dm", dlagent_memory_limit);
	proxyArgs[i++] = maxMemoryLimit;

	proxyArgs[i++] = "-XX:+ExitOnOutOfMemoryError";

	/*
	 * THE TRANSPORT CHOOSES THE CLASSPATH AND THE MAIN CLASS.
	 *
	 * Two agents, one GUC.  datalake.agent_transport is PGC_POSTMASTER
	 * precisely so this decision is made once, here, when the agent starts:
	 * a session-level switch would leave a backend speaking gRPC to a REST
	 * agent.
	 *
	 * -cp with an EXPLICIT, ORDERED list rather than -jar or a wildcard
	 * classpath entry.  The thin-jar layout stores the ~1 GB of shared dependencies
	 * once under core/ instead of inside each transport's fat jar, and the
	 * order is load-bearing: `bundle` 2.35.4 and `s3` 2.20.26 share 98.5% of
	 * their class names, so which one wins used to be fixed by the fat jar's
	 * packaging and would otherwise become whatever a wildcard expanded to
	 * that day, changing the REST path's behaviour, which must not change.
	 * contrib/datalake_agent's install-layout.sh writes that order into
	 * <transport>.cp.
	 */
	proxyArgs[i++] = "-cp";
	proxyArgs[i++] = classPath;
	proxyArgs[i++] = datalake_agent_transport == DATALAKE_AGENT_TRANSPORT_GRPC
		? DLAGENT_GRPC_MAIN_CLASS : DLAGENT_REST_MAIN_CLASS;

	snprintf(parentPid, sizeof(parentPid), "--parent.pid=%d", pid);
	proxyArgs[i++] = parentPid;

	/*
	 * Tell the agent to listen where the client will dial.
	 *
	 * datalake.agent_grpc_port is the FDW's idea of where the agent is; the
	 * agent's own default lives in DlAgentServer.  They agree only while both
	 * are left alone, so an operator who moves the port would otherwise move
	 * the client and not the server, and every query would fail against a
	 * perfectly healthy agent listening on the old one.
	 */
	if (datalake_agent_transport == DATALAKE_AGENT_TRANSPORT_GRPC)
	{
		snprintf(grpcPort, sizeof(grpcPort), "--dlagent.grpc.port=%d",
				 datalake_agent_grpc_port);
		proxyArgs[i++] = grpcPort;

		/*
		 * And tell it how large a message it may RECEIVE.
		 *
		 * Same argument as the port directly above, one layer down: the
		 * client's ceiling is read from this GUC by datalake_fdw, so unless
		 * the agent is told the same number the two disagree, and gRPC
		 * enforces the limit on the receiving side -- which for a request is
		 * the agent.  The symptom is a large commit failing with
		 * RESOURCE_EXHAUSTED under grpc and succeeding under rest.
		 */
		snprintf(rpcMaxMessageSize, sizeof(rpcMaxMessageSize),
				 "--dlagent.rpc_max_message_size=%d",
				 datalake_rpc_max_message_size_mb);
		proxyArgs[i++] = rpcMaxMessageSize;
	}

#ifndef USE_GOPHER
	/*
	 * Open-source build (configure --without-gopher): no libgopher is
	 * linked, so the agent must not select GopherFileIO -- it would try to
	 * connect to a gopher socket that no gophermeta process provides and
	 * fail every catalog metadata operation.  Turn gopher off on the agent
	 * side; it then uses the S3/HDFS FileIO driven by the volume connection
	 * info.  This overrides the gopher.enabled=true default packaged in the
	 * agent's application.properties.
	 */
	proxyArgs[i++] = "--gopher.enabled=false";
#endif

	proxyArgs[i] = NULL;

	execvp("java", proxyArgs);

	/*
	 * Still the forked child: no ereport and no exit(), both of which would
	 * run the worker's exit callbacks against its PGPROC.  stderr goes to
	 * the server log; the worker sees the exit status.
	 */
	fprintf(stderr, "datalake_proxy: could not start the dlagent JVM: %s\n",
			strerror(errno));
	_exit(EXIT_FAILURE);
}

