package cloud.elastic.dlagent.grpc.wire;

import io.grpc.MethodDescriptor;
import io.grpc.Status;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;

/**
 * Marshals the {@code Request} / {@code Response} messages of
 * {@code proto/dlagent.proto}, both of which are exactly
 * {@code { bytes payload = 1; }}.
 *
 * <p>WHY THIS IS HAND-WRITTEN. dlagent-grpc deliberately does not depend on
 * protobuf-java (see the long note in its pom): grpc-protobuf would require
 * 3.25.8, while hive-standalone-metastore, hbase-client and orc-core 1.5.1 pin
 * com.google.protobuf:protobuf-java to 2.5.0 on the shared classpath. The
 * payload contract reduces both messages to one length-delimited field,
 * which is a wire format small enough to implement exactly and pin with
 * evidence.
 *
 * <p>THE FORMAT, as emitted by protoc itself:
 *
 * <pre>
 *   payload = ""        -> (nothing at all; proto3 omits a default-valued field)
 *   payload = "{}"      -> 0a 02 7b 7d
 *   payload = "{\"a\":1}" -> 0a 07 7b 22 61 22 3a 31 7d
 *   127 bytes           -> 0a 7f ...
 *   128 bytes           -> 0a 80 01 ...
 * </pre>
 *
 * That is: tag byte {@code 0x0A} (field 1, wire type 2), a base-128 varint
 * length, then the bytes. The empty case is the one a hand-written encoder
 * would most plausibly get wrong by emitting {@code 0a 00}; a real protoc run
 * says otherwise, and {@code PayloadMarshallerTest} holds these exact byte
 * sequences as goldens generated by {@code protoc --encode}.
 *
 * <p>FORWARD COMPATIBILITY is implemented rather than assumed: {@link #parse}
 * skips fields it does not know, so a later field added to the proto by the
 * C++ side does not break this reader. Without that, extending the contract
 * would be a lockstep upgrade of both sides.
 */
public final class PayloadMarshaller implements MethodDescriptor.Marshaller<byte[]> {

    /** Field 1, wire type 2 (length-delimited): the only tag we emit. */
    private static final int PAYLOAD_TAG = 0x0A;

    private static final byte[] EMPTY = new byte[0];

    public static final PayloadMarshaller INSTANCE = new PayloadMarshaller();

    private PayloadMarshaller() {
    }

    @Override
    public InputStream stream(byte[] value) {
        return new ByteArrayInputStream(encode(value));
    }

    @Override
    public byte[] parse(InputStream stream) {
        try {
            return decode(readFully(stream));
        } catch (IOException e) {
            throw Status.INTERNAL
                    .withDescription("failed to read the gRPC payload")
                    .withCause(e)
                    .asRuntimeException();
        }
    }

    /** The wire bytes for a payload. Visible for the golden test. */
    static byte[] encode(byte[] payload) {
        if (payload == null || payload.length == 0) {
            // proto3 does not serialize a field that holds its default value,
            // so an empty payload is an empty message, not a zero-length field.
            return EMPTY;
        }
        byte[] len = varint(payload.length);
        byte[] out = new byte[1 + len.length + payload.length];
        out[0] = (byte) PAYLOAD_TAG;
        System.arraycopy(len, 0, out, 1, len.length);
        System.arraycopy(payload, 0, out, 1 + len.length, payload.length);
        return out;
    }

    /** The payload carried by a message. Visible for the golden test. */
    static byte[] decode(byte[] message) {
        if (message.length == 0) {
            return EMPTY;
        }
        Cursor c = new Cursor(message);
        byte[] payload = EMPTY;
        while (c.pos < message.length) {
            long tag = c.varint();
            if ((tag >>> 32) != 0) {
                // A field number is at most 29 bits, so a tag fits in 32;
                // narrowing a larger one would invent a field that is not
                // on the wire.
                throw c.malformed("a tag of " + Long.toUnsignedString(tag));
            }
            long field = tag >>> 3;
            int wireType = (int) (tag & 0x07);
            if (field == 1 && wireType == 2) {
                int len = c.length();
                payload = new byte[len];
                System.arraycopy(message, c.pos, payload, 0, len);
                c.pos += len;
            } else {
                c.skip(wireType);
            }
        }
        return payload;
    }

    private static byte[] varint(int value) {
        // Lengths are non-negative and bounded by the message size limit, so
        // five bytes is always enough.
        byte[] buf = new byte[5];
        int n = 0;
        int v = value;
        while ((v & ~0x7F) != 0) {
            buf[n++] = (byte) ((v & 0x7F) | 0x80);
            v >>>= 7;
        }
        buf[n++] = (byte) v;
        byte[] out = new byte[n];
        System.arraycopy(buf, 0, out, 0, n);
        return out;
    }

    private static byte[] readFully(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream(Math.max(32, in.available()));
        byte[] buf = new byte[8192];
        int n;
        while ((n = in.read(buf)) != -1) {
            out.write(buf, 0, n);
        }
        return out.toByteArray();
    }

    /** A position in the message, with the bounds checks in one place. */
    private static final class Cursor {
        private final byte[] buf;
        private int pos;

        Cursor(byte[] buf) {
            this.buf = buf;
        }

        long varint() {
            long result = 0;
            int shift = 0;
            while (true) {
                require(1);
                int b = buf[pos++] & 0xFF;
                result |= ((long) (b & 0x7F)) << shift;
                if ((b & 0x80) == 0) {
                    return result;
                }
                shift += 7;
                if (shift > 63) {
                    throw malformed("a varint longer than 10 bytes");
                }
            }
        }

        void skip(int wireType) {
            switch (wireType) {
                case 0:
                    varint();
                    break;
                case 1:
                    require(8);
                    pos += 8;
                    break;
                case 2:
                    int len = length();
                    pos += len;
                    break;
                case 5:
                    require(4);
                    pos += 4;
                    break;
                default:
                    // Wire types 3 and 4 are the removed "group" encoding; 6
                    // and 7 were never defined. Any of them means this is not
                    // the message we think it is, and silently continuing
                    // would hand the C side a truncated payload.
                    throw malformed("wire type " + wireType);
            }
        }

        /**
         * A length prefix, checked against what is left before it is narrowed:
         * casting first would turn 2^32+5 into 5 and parse a shorter message
         * than the one on the wire.
         */
        int length() {
            long len = varint();
            if (len < 0 || len > buf.length - pos) {
                throw malformed("a field claiming " + Long.toUnsignedString(len)
                        + " bytes with only " + (buf.length - pos) + " left");
            }
            return (int) len;
        }

        void require(int n) {
            // A remaining-bytes comparison, not pos + n: the length comes off
            // the wire, and the sum overflows to a negative int for a length
            // near Integer.MAX_VALUE, which would let a malformed message past
            // this check and fail later with a less useful exception.
            if (n < 0 || n > buf.length - pos) {
                throw malformed("a field claiming " + n + " bytes with only "
                        + (buf.length - pos) + " left");
            }
        }

        RuntimeException malformed(String what) {
            return Status.INTERNAL
                    .withDescription("malformed dlagent gRPC message: " + what)
                    .asRuntimeException();
        }
    }
}
