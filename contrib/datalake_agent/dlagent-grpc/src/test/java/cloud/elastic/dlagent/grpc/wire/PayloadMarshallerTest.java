package cloud.elastic.dlagent.grpc.wire;

import io.grpc.StatusRuntimeException;
import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Pins {@link PayloadMarshaller} to bytes that real protoc produced.
 *
 * <p>The marshaller is hand-written (see its javadoc for why), so "it looks
 * right" is not evidence. Every golden below was generated by running protoc
 * against the actual contract:
 *
 * <pre>
 *   printf 'payload: "{\\"a\\":1}"' \
 *     | protoc --proto_path=proto --encode=dlagent.v1.Request \
 *              proto/dlagent.proto | xxd -p
 * </pre>
 *
 * with protoc 3.21.12 on 2026-09-11. If the proto contract's field number or
 * type ever changes, these fail -- which is the point, because the C++ side
 * generates its stubs from that same file and the two must agree on the wire.
 */
public class PayloadMarshallerTest {

    private static byte[] hex(String s) {
        byte[] out = new byte[s.length() / 2];
        for (int i = 0; i < out.length; i++) {
            out[i] = (byte) Integer.parseInt(s.substring(i * 2, i * 2 + 2), 16);
        }
        return out;
    }

    private static byte[] utf8(String s) {
        return s.getBytes(StandardCharsets.UTF_8);
    }

    private void assertEncodes(String payload, String expectedHex) {
        assertArrayEquals(hex(expectedHex), PayloadMarshaller.encode(utf8(payload)),
                "encoding of " + payload + " diverged from what protoc emits");
        assertArrayEquals(utf8(payload), PayloadMarshaller.decode(hex(expectedHex)),
                "decoding protoc's bytes for " + payload + " lost the payload");
    }

    @Test
    public void matchesProtocForRepresentativePayloads() {
        assertEncodes("{}", "0a027b7d");
        assertEncodes("{\"a\":1}", "0a077b2261223a317d");
        // Multi-byte UTF-8 must be carried as bytes, not re-encoded: the length
        // prefix counts bytes (11) and not characters (8).
        assertEncodes("{\"n\":\"表\"}", "0a0b7b226e223a22e8a1a8227d");
    }

    /**
     * The empty payload is the case a hand-written encoder gets wrong: proto3
     * omits a field holding its default value, so an empty payload is an empty
     * MESSAGE, not {@code 0a 00}. protoc emits zero bytes here, measured.
     *
     * <p>It matters beyond pedantry: a successful operation with no body sends
     * an empty payload, and an extra two bytes would make
     * the C side see a one-byte payload of value 0 instead of no body.
     */
    @Test
    public void emptyPayloadIsAnEmptyMessage() {
        assertArrayEquals(new byte[0], PayloadMarshaller.encode(new byte[0]));
        assertArrayEquals(new byte[0], PayloadMarshaller.encode(null));
        assertArrayEquals(new byte[0], PayloadMarshaller.decode(new byte[0]));
    }

    /** The varint boundary, where a one-byte length becomes two. */
    @Test
    public void varintLengthBoundary() {
        byte[] p127 = new byte[127];
        java.util.Arrays.fill(p127, (byte) 'y');
        byte[] e127 = PayloadMarshaller.encode(p127);
        assertEquals(0x0a, e127[0] & 0xFF);
        assertEquals(0x7f, e127[1] & 0xFF, "127 must fit in a single-byte varint");
        assertEquals(129, e127.length);

        byte[] p128 = new byte[128];
        java.util.Arrays.fill(p128, (byte) 'y');
        byte[] e128 = PayloadMarshaller.encode(p128);
        assertEquals(0x0a, e128[0] & 0xFF);
        assertEquals(0x80, e128[1] & 0xFF, "128 must become a two-byte varint 80 01");
        assertEquals(0x01, e128[2] & 0xFF);
        assertEquals(131, e128.length);

        assertArrayEquals(p127, PayloadMarshaller.decode(e127));
        assertArrayEquals(p128, PayloadMarshaller.decode(e128));
    }

    /** A megabyte payload, i.e. a three-byte varint and a real file list. */
    @Test
    public void largePayloadRoundTrips() {
        byte[] big = new byte[1024 * 1024];
        for (int i = 0; i < big.length; i++) {
            big[i] = (byte) (i % 251);
        }
        assertArrayEquals(big, PayloadMarshaller.decode(PayloadMarshaller.encode(big)));
    }

    @Test
    public void roundTripsThroughTheMarshallerApi() {
        byte[] payload = utf8("{\"format-version\":2,\"current-snapshot-id\":7146290312398765432}");
        byte[] wire = PayloadMarshaller.encode(payload);
        assertArrayEquals(payload,
                PayloadMarshaller.INSTANCE.parse(new ByteArrayInputStream(wire)));
    }

    /**
     * A field the C++ side adds later must not break this reader, or extending
     * the contract would require upgrading both sides at once.
     */
    @Test
    public void skipsUnknownFields() {
        // field 2 varint (10 08 2a -> wrong; build it properly below)
        // field 1 = "{}"  : 0a 02 7b 7d
        // field 2 varint 42: 10 2a
        // field 3 length-delimited "zz": 1a 02 7a 7a
        // field 4 fixed64: 21 + 8 bytes
        // field 5 fixed32: 2d + 4 bytes
        byte[] withUnknowns = hex("0a027b7d" + "102a" + "1a027a7a"
                + "21" + "0102030405060708" + "2d" + "01020304");
        assertArrayEquals(utf8("{}"), PayloadMarshaller.decode(withUnknowns),
                "unknown fields must be skipped, not corrupt the payload");

        // Also when the unknown fields come BEFORE the payload.
        byte[] unknownsFirst = hex("102a" + "1a027a7a" + "0a027b7d");
        assertArrayEquals(utf8("{}"), PayloadMarshaller.decode(unknownsFirst));
    }

    /**
     * Truncation and the removed group wire types must fail loudly. Silently
     * returning a short payload would hand the C side a JSON document cut in
     * half, which its parser reports as a syntax error far from the cause.
     */
    @Test
    public void rejectsMalformedMessages() {
        StatusRuntimeException truncated = assertThrows(StatusRuntimeException.class,
                () -> PayloadMarshaller.decode(hex("0a0a7b7d")));
        assertTrue(truncated.getMessage().contains("malformed"), truncated.getMessage());

        StatusRuntimeException group = assertThrows(StatusRuntimeException.class,
                () -> PayloadMarshaller.decode(hex("0b")));
        assertTrue(group.getMessage().contains("wire type 3"), group.getMessage());
    }

    /** The varint encoding of any non-negative long, for crafting messages. */
    private static byte[] varint(long value) {
        java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream();
        long v = value;
        while ((v & ~0x7FL) != 0) {
            out.write((int) ((v & 0x7F) | 0x80));
            v >>>= 7;
        }
        out.write((int) v);
        return out.toByteArray();
    }

    private static byte[] concat(byte[]... parts) {
        java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream();
        for (byte[] p : parts) {
            out.write(p, 0, p.length);
        }
        return out.toByteArray();
    }

    /**
     * A 64-bit length or tag must not be narrowed to int: 2^32+5 would
     * become 5 and a different, shorter message would parse "successfully".
     */
    @Test
    public void rejectsLengthsAndTagsBeyondAnInt() {
        byte[] hello = "hello".getBytes(StandardCharsets.UTF_8);
        long wrapsToFive = (1L << 32) + 5;

        assertThrows(StatusRuntimeException.class,
                () -> PayloadMarshaller.decode(concat(hex("0a"), varint(wrapsToFive), hello)),
                "a payload length of 2^32+5 was read as 5");

        assertThrows(StatusRuntimeException.class,
                () -> PayloadMarshaller.decode(concat(varint((1L << 32) | 0x0A),
                        varint(hello.length), hello)),
                "a tag of 2^32+10 was read as field 1");

        // An unknown length-delimited field whose length wraps the same way.
        assertThrows(StatusRuntimeException.class,
                () -> PayloadMarshaller.decode(concat(hex("12"), varint((1L << 32) + 1),
                        hex("00"), hex("0a02"), "{}".getBytes(StandardCharsets.UTF_8))),
                "an unknown field's length of 2^32+1 was read as 1");

        assertThrows(StatusRuntimeException.class,
                () -> PayloadMarshaller.decode(concat(hex("0a"), varint(Integer.MAX_VALUE + 1L),
                        hello)),
                "a length above Integer.MAX_VALUE must be rejected");
    }
}
